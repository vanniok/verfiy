const languageCookie='verify_language';
let language=/(?:^|;\s*)verify_language=zh-CN(?:;|$)/.test(document.cookie)?'zh-CN':'en';
function t(text,values={}){
  const translated=language==='zh-CN'&&Object.hasOwn(zh,text)?zh[text]:text;
  return String(translated??'').replace(/\{(\w+)\}/g,(match,key)=>Object.hasOwn(values,key)?String(values[key]):match);
}
function applyLanguage(){
  document.documentElement.lang=language;
  document.title=t('Verify — Delivery Note Verification');
}
function setLanguage(value){
  language=value==='zh-CN'?'zh-CN':'en';
  document.cookie=`${languageCookie}=${language}; Path=/; Max-Age=31536000; SameSite=Strict`;
  applyLanguage();
}
